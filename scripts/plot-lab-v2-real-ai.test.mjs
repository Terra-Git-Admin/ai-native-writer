  creativeSchemaSource,
  /required:\s*\[[\s\S]*?"episodeFunction"[\s\S]*?"timePhase"[\s\S]*?"locationFunction"[\s\S]*?"dramaticMove"/,
  "Creative generation must plan episode function plus temporal and spatial rhythm."
